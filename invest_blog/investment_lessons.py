def ranked(recent=(),headlines='',today=None):
    today=today or datetime.now(timezone.utc).date();rotation=today.isocalendar().week%len(THEMES)
    order=THEMES[rotation:]+THEMES[:rotation];out=[]
    for i,t in enumerate(order):
        hits=sum(1 for w in t['keywords'] if w in headlines.casefold())
        out.append({**t,'recently_used':t['title'] in recent[:12],'score':hits,'order':i,'reason':('Повестка недели: '+', '.join(w for w in t['keywords'] if w in headlines.casefold())) if hits else 'Практическая тема для разбора компании или портфеля'})
    return sorted(out,key=lambda t:(t['recently_used'],-recent.index(t['title']) if t['recently_used'] else 0,-t['score'],t['order']))

def public_context(now=None,session=None):
    from .tech_news import parse_feed,RSS_HEADERS
    now=now or datetime.now(timezone.utc);session=session or requests.Session();titles=[]
    for source,url in [('РБК','https://rssexport.rbc.ru/rbcnews/news/30/full.rss'),('Интерфакс','https://www.interfax.ru/rss')]:
        try:
            with session.get(url,headers=RSS_HEADERS,timeout=(4,8),stream=True,allow_redirects=False) as response:
                response.raise_for_status();chunks=[];size=0
                for chunk in response.iter_content(65536):
                    size+=len(chunk)
                    if size>2_000_000:raise ValueError('Feed too large')
                    chunks.append(chunk)
            for item in parse_feed(b''.join(chunks),source):
                if item['published_at'] and timedelta(0)<=now-datetime.fromisoformat(item['published_at'])<=timedelta(days=7):titles.append(item['title'])
        except Exception:continue
    return '\n'.join(titles[:40])[:5000]

