  await page.locator('#waltPositions .goal-item').filter({hasText:'SPYx'}).filter({hasText:/150/}).waitFor();
  assert.equal((await overview()).combined.total_rub,'625000.00');
  fs.mkdirSync('docs/previews',{recursive:true});
