const assert=require('node:assert/strict');
require('node:fs').mkdirSync('docs/previews',{recursive:true});
const {chromium}=require(process.env.CONTENT_HUB_PLAYWRIGHT_PATH || 'playwright');
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CONTENT_HUB_BROWSER,headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  await page.route('https://cdn.jsdelivr.net/**',route=>route.abort());
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.CONTENT_HUB_URL||'http://127.0.0.1:8765');
  await page.locator('#status').filter({hasText:/Данные|Снимок|Часть/}).waitFor();
  await page.locator('.nav button').filter({hasText:'Редакция'}).click();
  await page.locator('#deskList .creator-entry').first().waitFor();
  assert.equal(await page.locator('.section.active').getAttribute('id'),'page-desk');
  await page.locator('#deskSearch').fill('Факты, источники');
  assert.equal(await page.locator('#deskList .creator-entry').count(),1);
  await page.locator('#deskSearch').fill('НЕСУЩЕСТВУЮЩИЙ МАТЕРИАЛ');
  assert.match(await page.locator('#deskList').innerText(),/Материалов.*нет/);
  await page.locator('#deskSearch').fill('');
  await page.screenshot({path:'docs/previews/preview-editorial.png',fullPage:false});
  await page.locator('.workspace-tabs button').filter({hasText:'Tech · Черновики'}).click();
  await page.locator('#techDrafts button').filter({hasText:'Редактировать'}).first().click();
  const original=await page.locator('#techBody').inputValue();
  await page.locator('#techBody').fill('Несохранённый текст');
  let dialogs=0;page.on('dialog',async dialog=>{dialogs++;await dialog.dismiss()});
  await page.locator('#techReset').click();
  assert.equal(await page.locator('#techBody').inputValue(),'Несохранённый текст');assert.equal(dialogs,1);
  await page.locator('.workspace-tabs button').filter({hasText:'Инвестиции'}).click();
  await page.locator('.workspace-tabs button').filter({hasText:'Tech · Черновики'}).click();
  assert.equal(await page.locator('#techBody').inputValue(),'Несохранённый текст');
  await page.locator('#techBody').fill(original);
  const panel=page.locator('#page-tech .writing-tools');await panel.locator('summary').click();
  await panel.locator('[data-field="title"]').fill('Роботы помогают создавать прототипы');
  await panel.locator('[data-field="description"]').fill('Проверяем редактор технологического блога.');
  await panel.locator('[data-field="keyword"]').fill('роботы');
  await panel.locator('[data-action="check"]').click();assert.match(await panel.locator('[data-field="feedback"]').innerText(),/в заголовке есть/);
  await page.route('**/api/editor/tools/translate',route=>route.fulfill({json:{text:'Робот помогает мастерам.'}}));
  await panel.locator('[data-action="translate"]').click();
  await panel.locator('[data-field="translation"]').waitFor({state:'visible'});
  assert.equal(await page.locator('#techBody').inputValue(),original);
  await panel.locator('[data-action="apply"]').click();
  assert.equal(await page.locator('#techBody').inputValue(),'Робот помогает мастерам.');
  await page.locator('#techBody').fill(original);
  await page.locator('.nav button').filter({hasText:'Портфель'}).click();
  assert.equal(await page.locator('.workspace-tabs #iisReviewLink').count(),1);
  await page.locator('.nav button').filter({hasText:'Tech · Новости'}).click();
  assert.equal(await page.locator('#page-news #techNewsList').count(),1);
  await page.locator('.workspace-tabs button').filter({hasText:'Публикация и история'}).click();
  assert.equal(await page.locator('#page-publishing #techPublishNow').count(),1);
  await page.evaluate(()=>location.hash='tech');await page.waitForTimeout(100);
  await page.screenshot({path:'docs/previews/preview-tech-editor.png',fullPage:true});
  // Reload restores the deep link and draft-specific SEO fields after opening it.
  await page.reload({waitUntil:'domcontentloaded'});await page.locator('#techDrafts button').filter({hasText:'Редактировать'}).first().click();
  const restored=page.locator('#page-tech .writing-tools');await restored.locator('summary').click();
  assert.equal(await restored.locator('[data-field="keyword"]').inputValue(),'роботы');
  // A failed content-plan request must leave the draft queue and other projects usable.
  await page.route('**/api/content-plan',route=>route.fulfill({status:503,json:{detail:'Temporarily unavailable'}}));
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('#fatal').filter({hasText:'Остальные разделы доступны'}).waitFor();
  await page.locator('.nav button').filter({hasText:'Редакция'}).click();
  await page.locator('#deskList .creator-entry').first().waitFor();
  await page.locator('.workspace-tabs button').filter({hasText:'Инвестиции'}).click();
  assert.ok(await page.locator('#editorQueue .editor-row').count()>0);
  await page.setViewportSize({width:390,height:844});
  await page.locator('.nav button').filter({hasText:'Редакция'}).click();await page.waitForTimeout(100);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'docs/previews/preview-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Workspace browser checks passed: queue, filters, navigation, unsaved text, translation preview, SEO persistence, mobile layout.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
